/** Lesson number n (1-based, wraps round) and the one after it. */
export function lessonAt(n) {
  const i = ((Math.floor(n) - 1) % LESSONS.length + LESSONS.length) % LESSONS.length;
  return { n: i + 1, ...LESSONS[i], next: LESSONS[(i + 1) % LESSONS.length].title };
}
